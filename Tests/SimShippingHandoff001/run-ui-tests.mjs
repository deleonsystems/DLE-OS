import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const v=JSON.parse(fs.readFileSync('tmp/shipping-handoff/released-fixture.json','utf8'));
let checks=0,calls=[];const check=(x,m)=>{assert.ok(x,m);checks++;};
const document={addEventListener(){}};
const window={DleOsRuntimeConfig:{environment:'SIMULATION'},fetch:async(url,options)=>{
  calls.push({url,options});return {ok:true,headers:{get:()=> 'application/json'},json:async()=>({rows:[v]})};
}};
vm.runInNewContext(fs.readFileSync('SRC/modules/shipping/shipping-handoff.js','utf8'),{window,document});
const ui=window.ShippingHandoff;
check(ui.date('2026-10-14')==='10/14/2026','date-only display does not shift timezones');
const a=v.authorizations[0];check(ui.workStatus(v,a)==='Released - SIM review required','released and cleared work ready');
check(ui.workStatus({...v,sourceCurrent:false},a).includes('hold'),'stale source prevents ready');
check(ui.workStatus(v,{...a,state:'HELD'}).includes('hold'),'held authorization prevents ready');
check(ui.workStatus({...v,clearances:v.clearances.map(c=>({...c,state:'HELD'}))},a).includes('hold'),'held clearance prevents ready');
check(ui.workStatus({...v,clearances:[]},a).includes('hold'),'missing clearance prevents ready');
const html=ui.detail(v,a);
for(const text of ['SIM-E2E-001-PO','0099999 / 010','0999999','SIM-ASSY-001 / A','10/14/2026','130 Packaging','Traveler v1','SIMULATED DEVELOPMENTAL','Shipping method · Review required','WILL_CALL','ground','Customer CoC','Serial list','Test results','FAI','Not established'])check(html.toLowerCase().includes(text.toLowerCase()),'detail '+text);
check(!/Start Packing|Shipment Processed|Confirm Dispatch|Print packing slip/.test(html),'read-only detail exposes no execution controls');
check(ui.detail({...v,context:{...v.context,customer:'<script>bad()</script>'}},undefined).includes('&lt;script&gt;'),'source evidence is escaped');
const mount={innerHTML:'',isConnected:true};await ui.renderShipping(mount);
check(mount.innerHTML.includes('data-shipping-count aria-live="polite">2'),'two partial authorizations visible without Accept');
check(mount.innerHTML.includes('Awaiting Release (0)'), 'no unreserved cleared quantity');
check(mount.innerHTML.includes('Shipment Reconciliation'),'processed shipments separately labeled');
check(!mount.innerHTML.includes('Accept Request'),'no Accept discovery gate');
check(calls.length===1&&calls[0].url.endsWith('/queue')&&!calls[0].options.method,'opening Shipping only GETs durable queue');
await ui.renderShipping(mount);check(calls.length===2&&mount.innerHTML.includes('data-shipping-count aria-live="polite">2'),'reload reads durable queue again');
window.fetch=async()=>{throw new Error('API unavailable');};await ui.renderShipping(mount);
check(mount.innerHTML.includes('API unavailable')&&!mount.innerHTML.includes('Released - SIM review required'),'API failure does not show cached ready work');
window.DleOsRuntimeConfig.environment='ISOLATED_DEVELOPMENT';check(ui.productionButton('0999999')===''&&!ui.isSim(),'developmental UI is SIM-only');
console.log(`PASS ${checks} Shipping handoff UI checks (isolated API fixture)`);
