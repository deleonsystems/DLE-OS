"""Verify C#-generated PDFs against the actual frozen Production projection.

Usage: python verify_projection_pdfs.py bound.json traveler.pdf bom.pdf
"""
import json
import re
import sys
from pathlib import Path

from pypdf import PdfReader


def normalized(value):
    return " ".join(str(value).replace("\u2013", "-").replace("\u2014", "-").replace("\u2011", "-").split())


package = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8-sig"))
checks = 0


def check(condition, message):
    global checks
    assert condition, message
    checks += 1


documents = {}
for kind, path in zip(("traveler", "bom"), sys.argv[2:4]):
    reader = PdfReader(path)
    pages = [page.extract_text() for page in reader.pages]
    documents[kind] = normalized(" ".join(pages))
    for index, text in enumerate(pages, 1):
        for value in ("NON-CONTROLLED COPY", "DLE-OS ELECTRONIC RECORD GOVERNS", "WO " + package["workOrderNumber"], "WO Traveler V1 | Definition V1", "Generated by", "UTC"):
            check(value in text, f"{kind} page {index}: {value}")
    for value in (package["context"]["customer"], package["context"]["assembly"], "10/14/2026", package["boundTraveler"]["id"], package["boundTraveler"]["definitionId"], "Frozen Labor V2"):
        check(value in documents[kind], f"{kind} frozen context: {value}")
    check("INTERNAL_RFQ" not in documents[kind], kind + " contains no internal RFQ notes")
    print(f"PASS {kind}: {len(pages)} pages")

traveler = documents["traveler"]
active = [op for op in package["boundTraveler"]["operations"] if op["classification"] == "PRODUCTION" and op["enabled"]]
check(len(active) == 12, "Actual frozen route has 12 active operations")
check([op["sequence"] for op in active] == list(range(20, 140, 10)), "Actual route preserves sequences 20-130")
for op in active:
    check(normalized(op["instructions"]) in traveler, "Complete frozen instruction: " + op["sourceOperationId"])
    for note in op["productionNotes"]:
        check(note["purpose"] == "PRODUCTION" and normalized(note["text"]) in traveler, "Complete production note: " + note["id"])
    for visual in op["visuals"]:
        check(visual["name"] in traveler, "Visual reference: " + visual["name"])
check("op-1 / 10 Kitting: retained in lineage, excluded from the active Production route." in traveler, "Kitting prerequisite retained")
check("op-9-reference.png" not in traveler, "Hand Solder stays text-only")

bom = documents["bom"]
check(len(package["bom"]) == 12, "Actual released BOM has 12 requirements")
for row in package["bom"]:
    check("Requirement: " + row["requirementId"] in bom, "Stable requirement identity: " + row["requirementId"])
    check(row["partNumber"] in bom, "Released identity: " + row["partNumber"])
opto = next(row for row in package["bom"] if row["partNumber"] == "SIM-OPTO-4")
check(opto["originalKittedQuantity"] == 12 and opto["acceptedMaterialApplied"] == 8 and opto["recordedKittedQuantity"] == 20 and opto["shortage"] == 0, "Actual final application quantities 12+8=20, short0")
for value in ("Original Kitting 12 EA + accepted material applied 8 EA = final recorded 20 EA", "SIM-AM-0000001", "SIM-PO-0001 / 010", "Counted Exact", package["kitting"]["submissionId"], package["source"]["releasedBomIdentity"]):
    check(value in bom, "Frozen final Kitting evidence: " + value)
check("Satisfied by the recorded completion disposition; no numerical measured quantity was recorded." in bom, "Unmeasured completion disposition remains truthful")
print(f"PASS: {checks} actual-projection PDF checks")
