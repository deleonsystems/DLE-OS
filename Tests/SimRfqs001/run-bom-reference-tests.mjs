import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../../SRC/workspaces/rfqs/bom-reference.js',import.meta.url),'utf8');
const node=quantity=>({dataset:{quantity},handlers:{},attrs:{},addEventListener(k,f){this.handlers[k]=f;},setAttribute(k,v){this.attrs[k]=v;}});
const rows=['0.1','0.2','50','1.125'].map(node),elements=Object.fromEntries(['bom-total','bom-selection','bom-clear'].map(k=>[k,node('')]));
const document={handlers:{},querySelectorAll:()=>rows,getElementById:k=>elements[k],addEventListener(k,f){this.handlers[k]=f;}};
const start=()=>vm.runInNewContext(source,{document});start();
const click=(i,options={})=>rows[i].handlers.click(options);
const summary=()=>elements['bom-selection'].textContent;
assert.equal(elements['bom-total'].textContent,'51.425');
click(0);assert.equal(summary(),'Selected: 1 lines · 0.1 components');
click(1,{ctrlKey:true});assert.equal(summary(),'Selected: 2 lines · 0.3 components');
click(0,{ctrlKey:true});assert.equal(summary(),'Selected: 1 lines · 0.2 components');
click(3,{shiftKey:true});assert.equal(summary(),'Selected: 4 lines · 51.425 components');
click(2);assert.equal(summary(),'Selected: 1 lines · 50 components');
document.handlers.keydown({key:'Escape'});assert.equal(summary(),'Selected: 0 lines · 0 components');
click(3);elements['bom-clear'].handlers.click();assert.equal(elements['bom-clear'].disabled,true);
rows[0].handlers.keydown({key:'Enter',preventDefault(){}});assert.equal(rows[0].attrs['aria-selected'],'true');
start();assert.equal(summary(),'Selected: 0 lines · 0 components');
assert.deepEqual(rows.map(r=>r.dataset.quantity),['0.1','0.2','50','1.125']);
assert.doesNotMatch(source,/fetch|localStorage|sessionStorage|XMLHttpRequest/);
console.log('PASS: exact decimal BOM totals, click/Ctrl/Shift selection, keyboard, clear, reload reset and immutable quantities without network/storage writes.');
