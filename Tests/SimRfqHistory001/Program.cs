using System.Text.Json;
using System.Security.Cryptography;
var root=Path.GetFullPath(args[0]);var json=new JsonSerializerOptions(JsonSerializerDefaults.Web);
string Hash(string f)=>Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(Path.Combine(root,"data",f))));
var before=new[]{"rfq-intakes.json","rfq-lanes.json"}.ToDictionary(f=>f,Hash);
var store=new SimRfqIntakeStore(root);var items=await store.ReadRfqCommercialList();
var records=JsonDocument.Parse(File.ReadAllText(Path.Combine(root,"data","rfq-intakes.json"))).RootElement.GetProperty("records").Deserialize<SimRfqIntakeRecord[]>(json)!;
int count=0;void Check(bool ok,string msg){if(!ok)throw new Exception(msg);count++;Console.WriteLine("PASS "+msg);}
foreach(var id in new[]{"RFQI-SIM-0036","RFQI-SIM-0042","RFQI-SIM-0045"}){
 var i=items.Single(i=>i.IntakeId==id);
 Check(i.Bucket=="HISTORY" && i.Status=="Awarded" && i.Commercial.Status=="SUBMITTED",id+" display-only award with commercial status retained");
 Check(i.History!.Orders.Single().Status==(id=="RFQI-SIM-0045"?"Pending contract acceptance":"Order accepted"),id+" correct separate acceptance status");
}
var item=items.Single(i=>i.IntakeId=="RFQI-SIM-0045") with{Bucket="SUBMITTED",Status="Submitted",History=null};
var order=records.Single(r=>r.IntakeId=="RFQI-SIM-0046");var p=order.OrderIntake!;
var draft=order with{Status="DRAFT",OrderIntake=p with{ReviewStatus="DRAFT"}};
var d=SimRfqHistoryProjection.Apply(item,[draft]);
Check(d.Bucket=="SUBMITTED" && d.History!.Orders.Single().Status=="Draft order linked","draft alone stays Submitted");
var wrong=order with{OrderIntake=p with{Quote=p.Quote! with{Reference=p.Quote.Reference with{ApprovalVersion=p.Quote.Reference.ApprovalVersion+1}}}};
Check(SimRfqHistoryProjection.Apply(item,[wrong]).History!.Orders.Length==0,"exact approval version match");
wrong=order with{OrderIntake=p with{Quote=p.Quote! with{Reference=p.Quote.Reference with{ApprovalId="other-approval"}}}};
Check(SimRfqHistoryProjection.Apply(item,[wrong]).Bucket=="SUBMITTED","different approval cannot award governing revision");
wrong=order with{OrderIntake=p with{Quote=p.Quote! with{Reference=p.Quote.Reference with{QuoteNumber="OTHER-R02"}}}};
Check(SimRfqHistoryProjection.Apply(item,[wrong]).Bucket=="SUBMITTED","quote number also matched");
var newer=item with{QuoteNumber="SIM-Q-0045-R02",Commercial=item.Commercial with{ApprovalVersion=2,ApprovalId="new-version"}};
Check(SimRfqHistoryProjection.Apply(newer,[order]).Bucket=="SUBMITTED","older awarded revision does not award newer revision");
var accepted=records.Single(r=>r.IntakeId=="RFQI-SIM-0044");
var acceptedItem=items.Single(i=>i.IntakeId=="RFQI-SIM-0036") with{Bucket="SUBMITTED",Status="Submitted",History=null};
Check(SimRfqHistoryProjection.Apply(acceptedItem,[accepted with{OrderIntake=p}]).Status=="Awarded","accepted order uses frozen acceptance package");
var noPo=order with{OrderIntake=p with{PoEvidence=[]}};
Check(SimRfqHistoryProjection.Apply(item,[noPo]).Bucket=="SUBMITTED","PO-backed submission required");
var second=order with{IntakeId="FIXTURE-SECOND",OrderIntake=p with{PoNumber="SECOND-PO",Facts=p.Facts with{Lines=[p.Facts.Lines[0] with{Quantity=5}]}}};
var multi=SimRfqHistoryProjection.Apply(item,[order,second]);
Check(multi.History!.Orders.Length==2 && multi.History.Orders.Any(o=>o.Quantity==5),"multiple orders and each quantity retained without allocation inference");
var undated=order with{OrderIntake=p with{History=[]}};
Check(SimRfqHistoryProjection.Apply(item,[undated]).History!.ActivityAt is null,"no invented award date when event evidence is missing");
var closedAt=DateTimeOffset.Parse("2026-10-01T12:00:00Z");
var closed=item with{Bucket="HISTORY",Status="Closed",Commercial=item.Commercial with{Status="CLOSED",ClosedAt=closedAt}};
var result=SimRfqHistoryProjection.Apply(closed,[order]);
Check(result.Status=="Closed" && result.History!.ActivityAt==closedAt,"explicit closed history and closure date preserved");
var expired=item with{Bucket="HISTORY",Status="Expired",Commercial=item.Commercial with{Status="EXPIRED"}};
result=SimRfqHistoryProjection.Apply(expired,[]);
Check(result.Status=="Expired" && result.History!.ActivityAt==expired.Commercial.ExpiresAt,"expired history retains actual expiration date");
var superseded=item with{Bucket="HISTORY",Status="Superseded",Commercial=item.Commercial with{Status="SUPERSEDED"}};
Check(SimRfqHistoryProjection.Apply(superseded,[]).Status=="Superseded","superseded history retained");
Check((await store.SearchOrderQuotes(order.Customer.CustomerId,"SIM-Q-0045-R01","SUBMITTED")).Length==1,"awarded display does not change quote reuse availability");
foreach(var f in before)Check(Hash(f.Key)==f.Value,"read-only projection preserves "+f.Key);
File.WriteAllText(Path.Combine(root,"history-projection.json"),JsonSerializer.Serialize(items,json));
Console.WriteLine($"PASS {count} checks");
